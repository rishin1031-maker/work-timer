const CACHE_PREFIX = 'work-timer:quote-id:'

function hashDateKey(dateKey) {
  let hash = 0
  for (let i = 0; i < dateKey.length; i += 1) {
    hash = (hash * 31 + dateKey.charCodeAt(i)) >>> 0
  }
  return hash
}

function toQuote(entry) {
  return { id: entry.id, text: entry.quote, author: entry.author }
}

function readCachedId(dateKey) {
  try {
    const raw = localStorage.getItem(`${CACHE_PREFIX}${dateKey}`)
    if (!raw) return null
    const id = Number(raw)
    return Number.isFinite(id) ? id : null
  } catch {
    return null
  }
}

function writeCachedId(dateKey, id) {
  try {
    localStorage.setItem(`${CACHE_PREFIX}${dateKey}`, String(id))
  } catch {
    /* ignore */
  }
}

function findById(id) {
  return quotes.find((entry) => entry.id === id) || null
}

/** Stable quote for a given shift-day key (or a refreshed override). */
export function getQuoteForDay(dateKey) {
  const key = dateKey || 'default'
  const cachedId = readCachedId(key)
  const cached = cachedId != null ? findById(cachedId) : null
  if (cached) return toQuote(cached)

  const entry = quotes[hashDateKey(key) % quotes.length]
  return toQuote(entry)
}

/** Pick a different random quote for the day and persist it. */
export function refreshQuoteForDay(dateKey, currentId) {
  const key = dateKey || 'default'
  const options =
    quotes.length > 1 ? quotes.filter((entry) => entry.id !== currentId) : quotes
  const next = options[Math.floor(Math.random() * options.length)]
  writeCachedId(key, next.id)
  return toQuote(next)
}
